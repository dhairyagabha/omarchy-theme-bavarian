#!/usr/bin/env python3
"""
Render every Omarchy config file in this theme from bin/palette.py.

The palette is the only place a colour is chosen. This script is the only
place a colour is written to disk. Editing a generated file by hand will be
undone the next time this runs — change the palette instead.

Run:  python3 bin/generate-theme.py
"""

from pathlib import Path

import palette as p

ROOT = Path(__file__).resolve().parent.parent

BANNER = "Bavarian — carbon, alpine white, Bavarian blue. Generated by bin/generate-theme.py."


def mix(a: str, b: str, t: float) -> str:
    """Blend two colours in sRGB space. t=0 -> a, t=1 -> b."""
    ar, ag, ab = p.rgb(a)
    br, bg, bb = p.rgb(b)
    return "#{:02x}{:02x}{:02x}".format(
        round(ar + (br - ar) * t),
        round(ag + (bg - ag) * t),
        round(ab + (bb - ab) * t),
    )


def write(name: str, body: str) -> None:
    path = ROOT / name
    path.write_text(body.lstrip("\n"))
    print(f"  wrote {name}")


