def colors_toml() -> str:
    order = [
        ("accent", "Bavarian blue. Focus, selection, active state."),
        ("cursor", "One step brighter than the accent so it is never lost."),
        ("foreground", "Body text. Deliberately below alpine white for long sessions."),
        ("background", "Carbon. The ground almost everything sits on."),
        ("selection_foreground", "Alpine white on the deep ALPINA blue below."),
        ("selection_background", "Deep ALPINA blue."),
    ]
    out = [f"# {BANNER}", "#", "# Level 1 structure, level 2 content, level 3 interaction,", "# level 4 emphasis, level 5 exceptional. See README.md.", ""]
    for key, note in order:
        out.append(f"# {note}")
        out.append(f'{key} = "{p.COLORS_TOML[key]}"')
    out.append("")
    out.append("# Normal ANSI. Restrained: these carry meaning, not decoration.")
    for i in range(8):
        out.append(f'color{i} = "{p.ansi(i)}"  # {p.ANSI_NAMES[i]}')
    out.append("")
    out.append("# Bright ANSI. Ambient-light tier — a lift of each hue, never a new one.")
    for i in range(8, 16):
        out.append(f'color{i} = "{p.ansi(i)}"  # {p.ANSI_NAMES[i]}')
    return "\n".join(out) + "\n"


