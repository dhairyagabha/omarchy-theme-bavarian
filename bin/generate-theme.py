# ===========================================================================
def btop_theme() -> str:
    def ramp(a: str, b: str, c: str) -> tuple[str, str, str]:
        return a, b, c

    values = {
        "main_bg": p.CARBON,
        "main_fg": p.TEXT,
        "title": p.ALPINE,
        "hi_fg": p.BAVARIAN,
        "selected_bg": p.ALPINA,
        "selected_fg": p.ALPINE,
        "inactive_fg": p.ALUMINIUM,
        "proc_misc": p.AMBIENT,
        "cpu_box": p.MACHINED,
        "mem_box": p.MACHINED,
        "net_box": p.MACHINED,
        "proc_box": p.MACHINED,
        "div_line": p.MACHINED,
    }
    # Every graph sweeps cool -> warm. Nothing reaches red until it matters.
    gradients = {
        "temp": ramp(p.VERDE, p.AMBER, p.MOTORSPORT),
        "cpu": ramp(p.FOCUS, p.AMBIENT, p.AMBER),
        "free": ramp(mix(p.VERDE, p.CARBON, 0.35), p.VERDE, p.VERDE_LIFT),
        "cached": ramp(mix(p.AMBIENT, p.CARBON, 0.35), p.AMBIENT, p.AMBIENT_LIFT),
        "available": ramp(mix(p.BAVARIAN, p.CARBON, 0.35), p.BAVARIAN, p.FOCUS),
        "used": ramp(p.AMBER, p.MOTORSPORT, p.MOTORSPORT_LIFT),
        "download": ramp(mix(p.FOCUS, p.CARBON, 0.35), p.FOCUS, p.AMBIENT_LIFT),
        "upload": ramp(mix(p.AMBER, p.CARBON, 0.35), p.AMBER, p.AMBER_LIFT),
    }

    notes = {
        "main_bg": "Carbon.",
        "main_fg": "Body text.",
        "title": "Box titles.",
        "hi_fg": "Keyboard shortcuts — the accent, because they are the interaction.",
        "selected_bg": "Deep ALPINA blue.",
        "inactive_fg": "Disabled text.",
        "proc_misc": "Mini graphs and detail text.",
        "cpu_box": "Box outlines — machined aluminium hairline.",
        "div_line": "Divider lines.",
    }

    lines = [f"# {BANNER}", ""]
    for key, value in values.items():
        if key in notes:
            lines.append(f"# {notes[key]}")
        lines.append(f'theme[{key}]="{value}"')
    lines.append("")
    lines.append("# Graph gradients. Each sweeps cool to warm; red is reserved for load")
    lines.append("# that actually deserves attention.")
    for name, (start, midv, end) in gradients.items():
        lines.append(f'theme[{name}_start]="{start}"')
        lines.append(f'theme[{name}_mid]="{midv}"')
        lines.append(f'theme[{name}_end]="{end}"')
    return "\n".join(lines) + "\n"


